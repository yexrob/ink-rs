"""Generate string-width tables in src/text/width_data.rs from Unicode 18.0.0.

Download these files into DATA_DIR:
https://www.unicode.org/Public/18.0.0/ucd/extracted/DerivedGeneralCategory.txt
https://www.unicode.org/Public/18.0.0/ucd/DerivedCoreProperties.txt
https://www.unicode.org/Public/18.0.0/ucd/EastAsianWidth.txt
https://www.unicode.org/Public/18.0.0/ucd/emoji/emoji-data.txt
https://www.unicode.org/Public/18.0.0/emoji/emoji-test.txt

Run: python3 -I scripts/gen_width_data.py [--check] DATA_DIR
"""

import argparse
from pathlib import Path
import re


def records(data_dir, filename):
    text = (data_dir / filename).read_text(encoding="utf-8")
    version = (
        f"# Version: {'18.0' if filename == 'emoji-test.txt' else '18.0.0'}\n"
        if filename.startswith("emoji-")
        else f"# {filename.removesuffix('.txt')}-18.0.0.txt\n"
    )
    if version not in text:
        raise ValueError(f"{filename}: expected Unicode 18.0.0 data")
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            yield [field.strip() for field in line.split(";")]


def properties(data_dir, filename, names):
    points = set()
    for fields in records(data_dir, filename):
        codepoints, prop = fields[:2]
        if prop in names:
            start, _, end = codepoints.partition("..")
            points.update(range(int(start, 16), int(end or start, 16) + 1))
    return points


def ranges(points):
    result = []
    for point in sorted(points):
        if result and result[-1][1] + 1 == point:
            result[-1] = (result[-1][0], point)
        else:
            result.append((point, point))
    return result


def generate(data_dir):
    mark = properties(data_dir, "DerivedGeneralCategory.txt", {"Mn", "Mc", "Me"})
    spacing_mark = properties(data_dir, "DerivedGeneralCategory.txt", {"Mc"})
    # string-width's visibleCharacterRegex excludes Mn/Me, but keeps Mc visible.
    # Its Surrogate category is omitted: Rust char contains Unicode scalars only.
    invisible = properties(
        data_dir, "DerivedGeneralCategory.txt", {"Mn", "Me", "Cc", "Cf"}
    ) | properties(data_dir, "DerivedCoreProperties.txt", {"Default_Ignorable_Code_Point"})
    pictographic = properties(data_dir, "emoji-data.txt", {"Extended_Pictographic"})
    emoji, variation, modifier_base, flags, tags = set(), set(), set(), set(), set()
    # Fully-qualified RGI entries supply the forms recognized by width.rs.
    # Keycaps and ZWJ sequences are handled there without sequence tables.
    for codepoints, status in records(data_dir, "emoji-test.txt"):
        if status != "fully-qualified":
            continue
        sequence = tuple(int(point, 16) for point in codepoints.split())
        if len(sequence) == 1:
            emoji.add(sequence[0])
        elif len(sequence) == 2:
            first, second = sequence
            if second == 0xFE0F:
                variation.add(first)
            elif 0x1F3FB <= second <= 0x1F3FF:
                modifier_base.add(first)
            elif all(0x1F1E6 <= point <= 0x1F1FF for point in sequence):
                flags.add((first - 0x1F1E6) * 26 + second - 0x1F1E6)
        elif sequence[-1] == 0xE007F:
            tags.add(sequence)

    tables = {
        "MARK": mark,
        "SPACING_MARK": spacing_mark,
        "INVISIBLE": invisible,
        "PICTOGRAPHIC": pictographic,
        "EMOJI": emoji,
        "EMOJI_VARIATION": variation,
        "EMOJI_MODIFIER_BASE": modifier_base,
        "FLAGS": flags,
        "EMOJI_TAGS": tags,
        "WIDE": properties(data_dir, "EastAsianWidth.txt", {"W", "F"}),
    }
    blocks = [
        "// Generated by scripts/gen_width_data.py from Unicode 18.0.0 data.\n"
        "// Do not edit by hand."
    ]
    for name, points in tables.items():
        if name == "EMOJI_TAGS":
            declaration = f"pub(super) const {name}: &[&str] = &["
            rows = [
                '    "' + "".join(f"\\u{{{point:x}}}" for point in sequence) + '",'
                for sequence in sorted(points)
            ]
        else:
            declaration = f"pub(super) const {name}: &[(u32, u32)] = &["
            rows = [f"    (0x{start:x}, 0x{end:x})," for start, end in ranges(points)]
        blocks.append("\n".join([declaration, *rows, "];"]))
    return ("\n\n".join(blocks) + "\n").encode("utf-8")


def check(path, generated):
    if not path.exists():
        print(f"Missing generated file: {path}")
        return 1
    current = path.read_bytes()
    if current == generated:
        print("width_data.rs is up to date")
        return 0
    pattern = rb"pub\(super\) const (\w+): [^\n]+\n.*?^\];\n"
    old = {match[1]: match[0] for match in re.finditer(pattern, current, re.M | re.S)}
    new = {match[1]: match[0] for match in re.finditer(pattern, generated, re.M | re.S)}
    for name in sorted(old.keys() | new.keys()):
        if old.get(name) != new.get(name):
            print(f"Table differs: {name.decode('ascii')}")
    if re.sub(pattern, b"", current, flags=re.M | re.S) != re.sub(
        pattern, b"", generated, flags=re.M | re.S
    ):
        print("Header or inter-table formatting differs")
    return 1


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("data_dir", type=Path)
    args = parser.parse_args()
    try:
        generated = generate(args.data_dir)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    path = Path(__file__).resolve().parents[1] / "src/text/width_data.rs"
    if args.check:
        return check(path, generated)
    path.write_bytes(generated)
    print(f"Generated {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
